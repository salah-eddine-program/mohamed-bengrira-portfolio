function applyTranslations(language) {
  const dictionary = translations[language] || translations.ar;
  document.documentElement.lang = language;
  document.documentElement.dir = language === 'ar' ? 'rtl' : 'ltr';
  document.body.dir = language === 'ar' ? 'rtl' : 'ltr';
  document.title = dictionary.title;
  $$('[data-i18n]').forEach((element) => {
    const key = element.dataset.i18n;
    if (Object.prototype.hasOwnProperty.call(dictionary, key)) {
      element.textContent = dictionary[key];
    }
  });
  updateLanguagePicker(language);
  renderSkills(dictionary.skills);
  renderTimeline(dictionary.experience, '#experienceTimeline');
  renderTimeline(dictionary.education, '#educationTimeline', true);
  renderLanguages(dictionary.languages);
  try { localStorage.setItem('mb-language', language); } catch (_) { /* storage may be blocked */ }
}

// Language selection; Arabic is the default, with full RTL layout support.
let savedLanguage = 'ar';
try {
  const candidate = localStorage.getItem('mb-language');
  if (candidate && translations[candidate]) savedLanguage = candidate;
} catch (_) { /* ignore storage restrictions */ }
applyTranslations(savedLanguage);
function updateLanguagePicker(language) {
  const selected = languageMenu.querySelector(`[data-language="${language}"]`);
  if (!selected) return;
  const selectedFlag = selected.querySelector('.flag-icon').cloneNode(true);
  const currentFlag = languageTrigger.querySelector('.flag-icon');
  currentFlag.replaceWith(selectedFlag);
  selectedFlag.classList.add('current-language-flag');
  $('#languageCurrentLabel').textContent = languageLabels[language];
  languageMenu.querySelectorAll('.language-option').forEach((option) => {
    option.setAttribute('aria-pressed', String(option.dataset.language === language));
  });
}

function closeLanguageMenu() {
  languageMenu.hidden = true;
  languageTrigger.setAttribute('aria-expanded', 'false');
}

languageTrigger.addEventListener('click', () => {
  const willOpen = languageMenu.hidden;
  languageMenu.hidden = !willOpen;
  languageTrigger.setAttribute('aria-expanded', String(willOpen));
});

languageMenu.querySelectorAll('.language-option').forEach((option) => {
  option.addEventListener('click', () => {
    applyTranslations(option.dataset.language);
    closeLanguageMenu();
    languageTrigger.focus();
  });
});

document.addEventListener('click', (event) => {
  if (!languagePicker.contains(event.target)) closeLanguageMenu();
});
document.addEventListener('keydown', (event) => {
  if (event.key === 'Escape') closeLanguageMenu();
});



