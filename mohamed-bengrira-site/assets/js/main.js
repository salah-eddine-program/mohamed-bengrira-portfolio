const $ = (selector, root = document) => root.querySelector(selector);
const $$ = (selector, root = document) => [...root.querySelectorAll(selector)];

function safeText(value) {
  return String(value).replace(/[&<>"']/g, (char) => ({
    '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;'
  })[char]);
}

function renderSkills(items) {
  const root = $('#skillsGrid');
  root.innerHTML = items.map((item) => `
    <article class="skill-card reveal">
      <div class="skill-card-head">
        <span class="skill-icon"><svg><use href="#${safeText(item.icon)}"></use></svg></span>
        <h3>${safeText(item.title)}</h3>
      </div>
      <p>${safeText(item.desc)}</p>
      <div class="skill-tags">${item.tags.map(tag => `<span>${safeText(tag)}</span>`).join('')}</div>
    </article>`).join('');
}

function renderTimeline(items, rootSelector, includeNote = false) {
  const root = $(rootSelector);
  root.innerHTML = items.map((item) => `
    <article class="timeline-item reveal">
      <span class="timeline-dot" aria-hidden="true"></span>
      <span class="timeline-date"><svg><use href="#i-calendar"></use></svg>${safeText(item.date)}</span>
      <h3>${safeText(item.title)}</h3>
      <div class="timeline-org">${safeText(item.org)}</div>
      ${item.desc ? `<p>${safeText(item.desc)}</p>` : ''}
      ${includeNote && item.note ? `<div class="timeline-note">${safeText(item.note)}</div>` : ''}
    </article>`).join('');
}

function renderLanguages(items) {
  $('#languageLevels').innerHTML = items.map((item) => `
    <article class="language-card reveal">
      <span class="language-symbol">${safeText(item.code)}</span>
      <div class="language-info">
        <b>${safeText(item.name)}</b>
        <small>${safeText(item.level)}</small>
        <div class="language-level" aria-label="${safeText(item.level)}">${Array.from({ length: 5 }, (_, index) => `<i class="${index < item.score ? 'filled' : ''}"></i>`).join('')}</div>
      </div>
    </article>`).join('');
}

